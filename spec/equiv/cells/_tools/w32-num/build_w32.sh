#!/usr/bin/env bash
# Build the bounded C/L leaves for a wave-32 numeric cell.
#
# Usage: build_w32.sh CELL_DIR
# Reads CELL_DIR/src/ops.txt (comma-separated twin handler names, may be
# empty) and CELL_DIR/src/fns.txt (one exported function name per line).
set -euo pipefail
CELL_DIR="$1"
W32="$(cd "$(dirname "$0")" && pwd)"
CELLS="$(cd "$W32/../.." && pwd)"
EQ="$(cd "$CELLS/.." && pwd)"
BUILD="$CELL_DIR/build"
mkdir -p "$BUILD"
OPS="$(cat "$CELL_DIR/src/ops.txt")"
FNS=()
while IFS= read -r f; do [ -n "$f" ] && FNS+=("$f"); done < "$CELL_DIR/src/fns.txt"
[ "${#FNS[@]}" -gt 0 ] || { echo "no functions in src/fns.txt" >&2; exit 2; }
if [ -n "$OPS" ]; then
  python3 "$CELLS/_tools/mk_leaf.py" \
    --ops "$OPS" --max-depth 4 --max-elem 5 \
    --out "$BUILD/twin_ops.h" --meta "$BUILD/twin_ops.meta.json"
  python3 "$CELLS/_tools/mk_leaf.py" \
    --ops "$OPS" --max-depth 4 --max-elem 5 --check "$BUILD/twin_ops.h"
  # Provenance gate: every selected handler body must appear verbatim (after
  # the same std::memcpy/std::memcmp -> bounded_* re-binding mk_leaf performs)
  # in src/l_leaf.cpp.  This fails the build if the L leg drifts from
  # twin/ops_ir.py.
  python3 - "$CELLS" "$CELL_DIR" "$OPS" <<'PY'
import sys, pathlib
cells, cell_dir, ops = sys.argv[1], sys.argv[2], sys.argv[3]
sys.path.insert(0, cells + "/../twin")
sys.dont_write_bytecode = True
import ops_ir
want = {o for o in ops.split(",") if o}
src = pathlib.Path(cell_dir, "src", "l_leaf.cpp").read_text()
missing = []
for op in ops_ir.OPS:
    if op["name"] not in want:
        continue
    for b in op["body"]:
        b = b.replace("std::memcpy(", "bounded_memcpy(").replace("std::memcmp(", "bounded_memcmp(")
        if b not in src:
            missing.append((op["name"], b))
if missing:
    for name, b in missing:
        print(f"PROVENANCE FAIL {name}: {b}", file=sys.stderr)
    raise SystemExit(1)
print(f"provenance OK: {len(want)} handler body/bodies verbatim in l_leaf.cpp", file=sys.stderr)
PY
fi
# TwinErr enum + core ordinal map, emitted from twin/gen.py and the contract
# (same source of record as mk_leaf.py's prologue).
python3 - "$CELLS" "$EQ" "$BUILD" <<'PY'
import sys, pathlib
cells, eq, build = sys.argv[1], sys.argv[2], sys.argv[3]
sys.path.insert(0, cells + "/../twin")
sys.dont_write_bytecode = True
import gen, hashlib, re
ords = {}
for m in re.finditer(r"EQUIV_ERR_([A-Z0-9_]+)\s*=\s*(\d+)",
                     pathlib.Path(eq, "contract", "error_kind.h").read_text()):
    ords[m.group(1)] = int(m.group(2))
L = ["// GENERATED by cells/_tools/w32/build_w32.sh -- DO NOT EDIT.",
     f"// twin/gen.py sha256 {hashlib.sha256(pathlib.Path(cells, '../twin/gen.py').read_bytes()).hexdigest()}",
     f"// contract/error_kind.h sha256 {hashlib.sha256(pathlib.Path(eq, 'contract', 'error_kind.h').read_bytes()).hexdigest()}",
     "#pragma once", "#include <cstdint>", "enum TwinErr : int32_t {"]
for e in gen.ERRORS:
    L.append(f"  {e['name']} = {e['id']},")
L.append("};")
L.append("// Mechanical TwinErr -> Core ScriptError ordinal (by core name).")
L.append("static inline int32_t core_ord(TwinErr e) {")
L.append("  switch (e) {")
for e in gen.ERRORS:
    if e["core"] in ords:
        L.append(f"    case {e['name']}: return {ords[e['core']]};")
L.append("    default: return 1;  // UNKNOWN_ERROR (twin-only sentinels)")
L.append("  }")
L.append("}")
pathlib.Path(build, "twin_err.h").write_text("\n".join(L) + "\n")
print(f"wrote {build}/twin_err.h", file=sys.stderr)
PY
# -fno-jump-tables: the generated core_ord switch would otherwise become a
# module-level switch table.  llvm-extract keeps the function but not the
# table definition, and a load from the resulting external constant is
# modelled as poison by Alive2 (spurious "target more poisonous" results).
CXX=(/usr/bin/clang++-20 -std=c++17 -O1 -fno-strict-aliasing -fno-jump-tables
     -I "$W32" -I "$CELL_DIR/src" -I "$BUILD" -S -emit-llvm -fno-discard-value-names)
"${CXX[@]}" "$CELL_DIR/src/c_leaf.cpp" -o "$BUILD/c_leaf.ll"
"${CXX[@]}" "$CELL_DIR/src/l_leaf.cpp" -o "$BUILD/l_leaf.ll"
for fn in "${FNS[@]}"; do
  for leg in c l; do
    /usr/lib/llvm-20/bin/llvm-extract --func="$fn" --recursive \
      "$BUILD/${leg}_leaf.ll" -o "$BUILD/${leg}_${fn}.bc"
    /usr/lib/llvm-20/bin/llvm-dis "$BUILD/${leg}_${fn}.bc" -o "$BUILD/${leg}_${fn}.ll"
  done
done
{
  printf 'cell=%s\n' "$(basename "$CELL_DIR")"
  printf 'fns=%s\n' "${FNS[*]}"
  printf 'mk_leaf ops=%s max_depth=4 max_elem=5\n' "${OPS:-<none>}"
  printf 'clang=%s\n' "$(/usr/bin/clang++-20 --version | head -1)"
  printf 'llvm=%s\n' "$(/usr/lib/llvm-20/bin/llvm-extract --version | head -1)"
  if [ -n "$OPS" ]; then
    printf 'twin_ops_sha256=%s\n' "$(sha256sum "$BUILD/twin_ops.h" | cut -d' ' -f1)"
  else
    printf 'twin_ops_sha256=<none: cell has no mk_leaf handler>\n'
  fi
  printf 'w32_common_sha256=%s\n' "$(sha256sum "$W32/w32_common.h" | cut -d' ' -f1)"
  printf 'root=%s\n' "$EQ"
} > "$BUILD/build.txt"
