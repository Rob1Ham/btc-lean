#!/usr/bin/env python3
"""Emit a bounded leaf instance of the twin's imperative IR.

Handler bodies are copied **verbatim** from `twin/ops_ir.py` (the same string
table `twin/gen.py` emits).  Only the stack representation constants are
re-bound to the cell's bounded domain.  No handler semantics are changed.

Usage:
  python3 mk_leaf.py --ops OP_SWAP,OP_DUP --out PATH [--meta PATH]
  python3 mk_leaf.py --ops ... --check PATH
"""
from __future__ import annotations
import argparse, hashlib, importlib.util, json, re, sys
sys.dont_write_bytecode = True
from pathlib import Path

HERE = Path(__file__).resolve().parent
def _find_equiv() -> Path:
    for p in (HERE, *HERE.parents):
        if (p / "contract" / "error_kind.h").is_file():
            return p
    raise SystemExit(f"cannot locate spec/equiv from {HERE}")
EQUIV = _find_equiv()
TWIN = EQUIV / "twin"
CONTRACT = EQUIV / "contract" / "error_kind.h"

def sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()

def load_gen():
    sys.path.insert(0, str(TWIN))
    spec = importlib.util.spec_from_file_location("twin_gen_ro", TWIN / "gen.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    spec2 = importlib.util.spec_from_file_location("twin_ops_ro", TWIN / "ops_ir.py")
    ops = importlib.util.module_from_spec(spec2)
    spec2.loader.exec_module(ops)
    return mod, ops

def core_ordinals():
    out = {}
    for m in re.finditer(r"EQUIV_ERR_([A-Z0-9_]+)\s*=\s*(\d+)", CONTRACT.read_text()):
        out[m.group(1)] = int(m.group(2))
    return out

def render(selected, max_depth, max_elem):
    g, o = load_gen()
    ords = core_ordinals()
    if selected:
        table = [x for x in o.OPS if x["name"] in selected]
        missing = selected - {x["name"] for x in table}
        if missing:
            raise SystemExit(f"unknown op(s): {sorted(missing)}")
    else:
        table = list(o.OPS)
    L = []
    L.append("// GENERATED by cells/_tools/mk_leaf.py -- DO NOT EDIT.")
    L.append(f"// Source of record: twin/ops_ir.py sha256 {sha(TWIN/'ops_ir.py')}")
    L.append(f"// Generator: twin/gen.py sha256 {sha(TWIN/'gen.py')}")
    L.append(f"// Contract: contract/error_kind.h sha256 {sha(CONTRACT)}")
    L.append(f"// Bounded leaf domain: stack depth {max_depth}, element size {max_elem}.")
    L.append("// Handler bodies are verbatim from twin/ops_ir.py OPS.")
    L.append("#pragma once")
    L.append("#include <cstdint>")
    L.append("#include <cstddef>")
    L.append("#include <cstring>")
    L.append("namespace twinleaf {")
    L.append(f"#define TWINLEAF_MAX_ELEM {max_elem}")
    L.append(f"constexpr uint32_t MAX_SCRIPT_ELEMENT_SIZE = {max_elem};")
    L.append(f"constexpr uint32_t MAX_STACK_SIZE = {max_depth};")
    L.append("")
    L.append("enum TwinErr : int32_t {")
    for e in g.ERRORS:
        L.append(f"  {e['name']} = {e['id']},  // core={e['core']} lean={e['lean']}")
    L.append("};")
    L.append("")
    L.append("struct ScriptFlags { bool p2sh, dersig, cltv, csv, nullDummy, witness, taproot; };")
    L.append("struct PolicyFlags { bool minimalData, minimalIf, nullFail, strictEnc, constScriptCode, cleanstack;")
    L.append("  bool sigPushOnly, lowS, witnessPubkeyType, discourageUpgradableNops;")
    L.append("  bool discourageUpgradableWitnessProgram, discourageUpgradablePubkeyType;")
    L.append("  bool discourageOpSuccess, discourageUpgradableTaprootVersion; };")
    L.append("enum class SigVersion : uint8_t { Base, WitnessV0, Tapscript };")
    L.append("struct Ctx { ScriptFlags flags; PolicyFlags pol; SigVersion sv; };")
    L.append("enum class Kind : uint8_t { PushBytes, PushNum, Op };")
    L.append("struct Decoded { Kind kind; const uint8_t* data; uint32_t dlen; uint32_t wire; uint32_t next; };")
    L.append("struct Stack { uint32_t n; uint32_t len[MAX_STACK_SIZE]; uint8_t e[MAX_STACK_SIZE][MAX_SCRIPT_ELEMENT_SIZE]; };")
    L.append("struct State { Stack stack; Stack alt; Stack saved; bool vf[1]; uint32_t vf_n, opCount;")
    L.append("  uint32_t codeSep, codeSepPos, opcodeIndex; int64_t vwLeft; bool has_vw; };")
    L.append("")
    L.append("// Bounded, loop-free memory primitives.  Extensionally equal to")
    L.append("// std::memcpy/std::memcmp for len <= MAX_SCRIPT_ELEMENT_SIZE (2).")
    L.append("static inline __attribute__((always_inline)) void bounded_memcpy(uint8_t* d, const uint8_t* s, uint32_t len) {")
    L.append("  if (len >= 1) d[0] = s[0];")
    L.append("  if (len >= 2) d[1] = s[1];")
    L.append("}")
    L.append("static inline __attribute__((always_inline)) int bounded_memcmp(const uint8_t* a, const uint8_t* b, uint32_t len) {")
    L.append("  if (len >= 1 && a[0] != b[0]) return (int)a[0] - (int)b[0];")
    L.append("  if (len >= 2 && a[1] != b[1]) return (int)a[1] - (int)b[1];")
    L.append("  return 0;")
    L.append("}")
    L.append("static inline __attribute__((always_inline)) TwinErr st_push(Stack& s, const uint8_t* data, uint32_t len) {")
    L.append("  if (len > MAX_SCRIPT_ELEMENT_SIZE) return TWIN_PUSH_SIZE;")
    L.append("  if (s.n >= MAX_STACK_SIZE) return TWIN_STACK_SIZE;")
    L.append("  if (len != 0) bounded_memcpy(s.e[s.n], data, len);")
    L.append("  s.len[s.n] = len; s.n += 1; return TWIN_OK;")
    L.append("}")
    L.append("static inline __attribute__((always_inline)) const uint8_t* st_top(const Stack& s, uint32_t k, uint32_t& len) {")
    L.append("  const uint32_t i = s.n - k; len = s.len[i]; return s.e[i];")
    L.append("}")
    L.append("static inline __attribute__((always_inline)) TwinErr st_push_copy(Stack& s, uint32_t k) {")
    L.append("  if (s.n < k) return TWIN_INVALID_STACK_OPERATION;")
    L.append("  const uint32_t i = s.n - k; const uint32_t l = s.len[i];")
    L.append("  if (l > MAX_SCRIPT_ELEMENT_SIZE) return TWIN_PUSH_SIZE;")
    L.append("  if (s.n >= MAX_STACK_SIZE) return TWIN_STACK_SIZE;")
    L.append("  bounded_memcpy(s.e[s.n], s.e[i], l); s.len[s.n] = l; s.n += 1; return TWIN_OK;")
    L.append("}")
    L.append("static inline __attribute__((always_inline)) uint32_t encode_num(int64_t v, uint8_t* out) {")
    L.append("  if (v == 0) return 0;")
    L.append("  const bool neg = v < 0;")
    L.append("  uint64_t a = neg ? (static_cast<uint64_t>(-(v + 1)) + 1u) : static_cast<uint64_t>(v);")
    L.append("  uint32_t n = 0;")
    L.append("  if (a != 0) { out[n++] = static_cast<uint8_t>(a & 0xffu); a >>= 8; }")
    L.append("  if (a != 0) { out[n++] = static_cast<uint8_t>(a & 0xffu); a >>= 8; }")
    L.append("  if (a != 0) { out[n++] = static_cast<uint8_t>(a & 0xffu); a >>= 8; }")
    L.append("  if (a != 0) { out[n++] = static_cast<uint8_t>(a & 0xffu); a >>= 8; }")
    L.append("  if ((out[n - 1] & 0x80u) != 0) out[n++] = neg ? 0x80u : 0x00u;")
    L.append("  else if (neg) out[n - 1] = static_cast<uint8_t>(out[n - 1] | 0x80u);")
    L.append("  return n;")
    L.append("}")
    L.append("static inline __attribute__((always_inline)) TwinErr st_push_num(Stack& s, int64_t v) {")
    L.append("  uint8_t tmp[4]; const uint32_t n = encode_num(v, tmp); return st_push(s, tmp, n);")
    L.append("}")
    L.append("// Bounded CScriptNum decode for len <= 2 (cell domain).")
    L.append("static inline __attribute__((always_inline)) TwinErr decode_num(const uint8_t* d, uint32_t len, bool minimal,")
    L.append("                                  uint32_t maxlen, int64_t& out) {")
    L.append("  if (len > maxlen || len > 2) return TWIN_SCRIPTNUM;")
    L.append("  if (len == 0) { out = 0; return TWIN_OK; }")
    L.append("  const bool neg = (d[len - 1] & 0x80u) != 0;")
    L.append("  if (minimal && (d[len - 1] & 0x7fu) == 0 && (len == 1 || (d[len - 2] & 0x80u) == 0))")
    L.append("    return TWIN_SCRIPTNUM;")
    L.append("  uint32_t v = d[0];")
    L.append("  if (len >= 2) v |= static_cast<uint32_t>(d[1]) << 8;")
    L.append("  if (neg) { v &= ~(0x80u << (8u * (len - 1))); out = -static_cast<int64_t>(v); }")
    L.append("  else out = static_cast<int64_t>(v);")
    L.append("  return TWIN_OK;")
    L.append("}")
    L.append("static inline __attribute__((always_inline)) bool cast_to_bool(const uint8_t* d, uint32_t len) {")
    L.append("  if (len == 0) return false;")
    L.append("  if (len == 1) return !(d[0] == 0 || d[0] == 0x80);")
    L.append("  if (len == 2) { if (d[0] != 0) return true; return !(d[1] == 0 || d[1] == 0x80); }")
    L.append("  return false;")
    L.append("}")
    L.append("")
    for op in table:
        wires = ", ".join(f"0x{int(w):02x}" for w in op["wires"])
        L.append(f"// {op['name']} (wire {wires}) -- Lean: {op['lean']}")
        L.append(f"static inline __attribute__((always_inline)) TwinErr op_{op['name']}(State& st, const Ctx& ctx, const Decoded& d) {{")
        for b in op["body"]:
            b = b.replace("std::memcpy(", "bounded_memcpy(").replace("std::memcmp(", "bounded_memcmp(")
            L.append("  " + b)
        L.append("}")
        L.append("")
    L.append("// Mechanical TwinErr -> Core ScriptError ordinal (by core name).")
    L.append("static inline __attribute__((always_inline)) int32_t core_ord(TwinErr e) {")
    L.append("  switch (e) {")
    for e in g.ERRORS:
        core = e["core"]
        val = ords.get(core, 1)
        L.append(f"    case {e['name']}: return {val};" + ("" if core in ords else f"  // unmapped: {core}"))
    L.append("  }")
    L.append("  return 1;")
    L.append("}")
    L.append("}  // namespace twinleaf")
    L.append("")
    return "\n".join(L)

def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--ops", default="", help="comma-separated handler names (default: all)")
    ap.add_argument("--out")
    ap.add_argument("--check")
    ap.add_argument("--meta")
    ap.add_argument("--max-depth", type=int, default=4)
    ap.add_argument("--max-elem", type=int, default=2)
    a = ap.parse_args()
    selected = {s for s in a.ops.split(",") if s}
    src = render(selected, a.max_depth, a.max_elem)
    if a.check:
        try: old = Path(a.check).read_text()
        except FileNotFoundError:
            print(f"DRIFT: {a.check} missing", file=sys.stderr); return 1
        if old != src:
            print(f"DRIFT: {a.check} is not reproducible", file=sys.stderr); return 1
        print(f"OK: {a.check} matches mk_leaf output", file=sys.stderr)
    if a.out:
        Path(a.out).parent.mkdir(parents=True, exist_ok=True)
        Path(a.out).write_text(src)
        print(f"wrote {a.out} ({len(src)} bytes)", file=sys.stderr)
    if a.meta:
        meta = {"gen_sha256": sha(TWIN/"gen.py"), "ops_ir_sha256": sha(TWIN/"ops_ir.py"),
                "contract_h_sha256": sha(CONTRACT),
                "leaf_sha256": hashlib.sha256(src.encode()).hexdigest(),
                "max_depth": a.max_depth, "max_elem": a.max_elem,
                "ops": sorted(selected)}
        Path(a.meta).write_text(json.dumps(meta, indent=2) + "\n")
        print(f"wrote {a.meta}", file=sys.stderr)
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
