#include <cstdint>
#include "twin.cpp"
#include "error_kind.h"

using twin::TwinErr;
using twin::TWIN_OK;
using twin::TWIN_SCRIPTNUM;

// L leg: the twin's CScriptNum decode, unrolled.
//
//   twin/runtime.inc:167-188  decode_num(b, len, minimal, maxSize, out)
//       if (len > maxSize) return TWIN_SCRIPTNUM;
//       if (minimal && len > 0) {
//         if ((b[len - 1] & 0x7fu) == 0) {
//           if (len <= 1 || (b[len - 2] & 0x80u) == 0) return TWIN_SCRIPTNUM;
//         }
//       }
//       if (len == 0) { out = 0; return TWIN_OK; }
//       uint64_t v = 0;
//       for (i = 0; i < len; ++i) { byte = b[i]; if (i+1==len) byte &= 0x7f; v |= byte << 8i; }
//       ...
//
// The for loop is the only change: it is unrolled for len <= 5, which is the
// cell domain (the width guard returns first for any larger len because
// maxSize is 4 or 5).  The minimality guard, the value assembly and the sign
// handling are verbatim.  The decode helper is in runtime.inc, not in the
// generated handler table, so it is transcribed rather than generated by
// mk_leaf.py (whose bounded copy stops at two bytes).
//
// Mapping to the contract ordinal is the twin's TWIN_SCRIPTNUM ->
// EQUIV_ERR_SCRIPTNUM; TWIN_OK -> EQUIV_ERR_OK.  No other result is possible
// in this helper.
static uint32_t w32_core_ord(TwinErr e) {
  return e == TWIN_OK ? (uint32_t)EQUIV_ERR_OK
                      : (uint32_t)EQUIV_ERR_SCRIPTNUM;
}

static TwinErr lean_decode_num(const uint8_t* b, uint32_t len, bool minimal,
                               uint32_t maxSize, int64_t& out) {
  if (len > maxSize) return TWIN_SCRIPTNUM;
  if (minimal && len > 0) {
    if ((b[len - 1] & 0x7fu) == 0) {
      if (len <= 1 || (b[len - 2] & 0x80u) == 0) return TWIN_SCRIPTNUM;
    }
  }
  if (len == 0) {
    out = 0;
    return TWIN_OK;
  }
  uint64_t v = 0;
  if (len >= 1) v |= (uint64_t)b[0];
  if (len >= 2) v |= (uint64_t)b[1] << 8;
  if (len >= 3) v |= (uint64_t)b[2] << 16;
  if (len >= 4) v |= (uint64_t)b[3] << 24;
  if (len >= 5) v |= (uint64_t)b[4] << 32;
  const bool neg = (b[len - 1] & 0x80u) != 0;
  if (neg) v &= ~(0x80ull << (8u * (len - 1)));
  out = neg ? -static_cast<int64_t>(v) : static_cast<int64_t>(v);
  return TWIN_OK;
}

static uint64_t w32_dec_pack(uint32_t res, uint32_t err, int64_t v) {
  return (uint64_t)(res & 3u) | ((uint64_t)(err & 0x3fu) << 2) |
         ((uint64_t)v << 8);
}

extern "C" uint64_t cell_decnum(uint8_t b0, uint8_t b1, uint8_t b2,
                                uint8_t b3, uint8_t b4, uint8_t len,
                                uint8_t minimal, uint8_t wide) {
  const uint8_t v[5] = {b0, b1, b2, b3, b4};
  // Cell domain: operand length is three bits (0..7).  Lengths 0..5 reach
  // the value path; 6 and 7 are wider than both maxSize choices and exercise
  // the width rejection.  Masking is identical on both legs.
  const uint32_t len_m = len & 7u;
  const uint32_t maxsize = wide ? 5u : 4u;
  int64_t out = 0;
  const TwinErr e = lean_decode_num(v, len_m, minimal != 0, maxsize, out);
  if (e != TWIN_OK) return w32_dec_pack(0, w32_core_ord(e), 0);
  return w32_dec_pack(1, (uint32_t)EQUIV_ERR_OK, out);
}
