#!/usr/bin/env python3
"""Emit the C and L name-id tables and the Cryptol table for SCR-173.

Inputs are two independent transcriptions:
  core_names.txt  -- Bitcoin Core script.cpp:19-157 GetOpName cases
  lean_names.txt  -- PDW68.lean opNameWire equations
Ids are assigned from the union of the two name sets, sorted by name, with
0 reserved for "OP_UNKNOWN".  The generator never compares the two tables:
a divergence must surface as an Alive2 counterexample / SAW failure, not as a
build error.  src/check_names.py is the separate (non-proof) reviewer check.
"""
from __future__ import annotations

import sys
from pathlib import Path


def read_table(path: Path) -> dict[int, str]:
    out: dict[int, str] = {}
    for line in path.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        wire, name = line.split(None, 1)
        w = int(wire, 16)
        if not 0 <= w <= 0xFF:
            raise SystemExit(f"{path}: wire out of range {wire}")
        if w in out:
            raise SystemExit(f"{path}: duplicate wire {wire}")
        out[w] = name.strip()
    return out


def emit_ids(table: dict[int, str], fn: str, path: Path) -> None:
    lines = [
        f"// GENERATED by src/gen_opname.py -- {path.name}",
        "// Ids index the sorted union of both transcriptions; 0 = OP_UNKNOWN.",
        "#pragma once",
        "#include <cstdint>",
        f"static inline __attribute__((always_inline)) uint32_t {fn}(uint32_t w) {{",
        "  switch (w) {",
    ]
    for w in range(0x100):
        if w in table:
            lines.append(f'    case 0x{w:02x}: return /* {table[w].replace("*/", "* /")} */ {IDS[table[w]]}u;')
    lines.append("    default: return 0u;")
    lines.append("  }")
    lines.append("}")
    path.write_text("\n".join(lines) + "\n")


def emit_cry(core: dict[int, str], path: Path) -> None:
    ids = [IDS[core[w]] if w in core else 0 for w in range(0x100)]
    lines = [
        "module CellOpName where",
        "",
        "// Independent Cryptol table for GetOpName: id 0 = OP_UNKNOWN.",
        "// Source: script.cpp:19-157.  Ids are the generator's sorted union.",
        "nameId : [8] -> [32]",
        "nameId w = ids @ w",
        "",
        "ids : [256][32]",
        "ids = [",
    ]
    for i in range(0, 0x100, 16):
        chunk = ", ".join(str(v) for v in ids[i:i + 16])
        lines.append("  " + chunk + ("," if i + 16 < 0x100 else ""))
    lines.append("]")
    path.write_text("\n".join(lines) + "\n")


def main(here: Path, build: Path) -> int:
    core = read_table(here / "core_names.txt")
    lean = read_table(here / "lean_names.txt")

    global IDS
    all_names = sorted(set(core.values()) | set(lean.values()))
    IDS = {name: i + 1 for i, name in enumerate(all_names)}

    build.mkdir(parents=True, exist_ok=True)
    emit_ids(core, "core_opname_id", build / "opname_core.inc")
    emit_ids(lean, "lean_opname_id", build / "opname_lean.inc")
    emit_cry(core, build / "cell.cry")
    return 0


if __name__ == "__main__":
    sys.exit(main(Path(__file__).resolve().parent, Path(sys.argv[1])))
