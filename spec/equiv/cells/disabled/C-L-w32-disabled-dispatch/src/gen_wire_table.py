#!/usr/bin/env python3
"""Emit the L-leg wire-class tables from the twin's own sources.

Derivation (no hand transcription of the handler table):
  * OPS + wire lists: spec/equiv/twin/ops_ir.py (imported, same file
    twin/gen.py consumes).
  * disabled set: the `disabled_wire` switch in spec/equiv/twin/runtime.inc.
  * structural push sets: spec/equiv/twin/gen.py validate_wire_table
    (0x00..0x4e direct pushes; 0x4f and 0x51..0x60 push-numbers).

A handler whose body returns TWIN_BAD_OPCODE is classed BAD; every other
handler is DISPATCHED.  The script fails if the five classes do not partition
0x00..0xff exactly once, so a hole (which would fall into dispatch()'s
safety net) is a build error, not a silent verdict.
"""
from __future__ import annotations

import hashlib
import importlib.util
import re
import sys
from pathlib import Path

sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent


def find_equiv() -> Path:
    for p in (HERE, *HERE.parents):
        if (p / "contract" / "error_kind.h").is_file():
            return p
    raise SystemExit(f"cannot locate spec/equiv from {HERE}")


EQ = find_equiv()
TWIN = EQ / "twin"


def sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def load_ops():
    sys.path.insert(0, str(TWIN))
    spec = importlib.util.spec_from_file_location("w32_ops_ir", TWIN / "ops_ir.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod.OPS


def disabled_wires() -> set[int]:
    text = (TWIN / "runtime.inc").read_text()
    m = re.search(r"static bool disabled_wire\(uint32_t w\) \{(.*?)\n\}", text, re.S)
    if not m:
        raise SystemExit("cannot locate disabled_wire in twin/runtime.inc")
    return {int(x, 16) for x in re.findall(r"0x([0-9a-fA-F]{2})", m.group(1))}


def main(out: Path) -> int:
    ops = load_ops()
    pushbytes = set(range(0x00, 0x4f))
    pushnum = {0x4f} | set(range(0x51, 0x61))
    disabled = disabled_wires()

    bad: set[int] = set()
    dispatched: set[int] = set()
    for op in ops:
        body = "\n".join(op["body"])
        target = bad if "TWIN_BAD_OPCODE" in body else dispatched
        for w in op["wires"]:
            target.add(w)

    order = [("W32_DISABLED", disabled), ("W32_PUSHBYTES", pushbytes),
             ("W32_PUSHNUM", pushnum), ("W32_BAD", bad),
             ("W32_DISPATCHED", dispatched)]
    seen: dict[int, str] = {}
    for name, s in order:
        for w in s:
            if w in seen:
                raise SystemExit(f"class overlap at {w:#04x}: {seen[w]} / {name}")
            if not 0 <= w <= 0xff:
                raise SystemExit(f"{name}: wire out of range {w}")
            seen[w] = name
    missing = [w for w in range(0x100) if w not in seen]
    if missing:
        raise SystemExit("unclassified wires: " + ", ".join(f"{w:#04x}" for w in missing))

    lines = [
        "// GENERATED by src/gen_wire_table.py -- DO NOT EDIT.",
        f"// twin/ops_ir.py sha256 {sha(TWIN / 'ops_ir.py')}",
        f"// twin/gen.py sha256 {sha(TWIN / 'gen.py')}",
        f"// twin/runtime.inc sha256 {sha(TWIN / 'runtime.inc')}",
        "// Five-way partition of the 0x00..0xff wire space; checked at build.",
        "// Expressions, not arrays: llvm-extract turns referenced internal",
        "// constant arrays into external declarations, which Alive2 cannot read.",
        "#pragma once",
        "#include <cstdint>",
        "namespace w32wire {",
    ]
    for name, s in order:
        members = sorted(s)
        if not members:
            lines.append(f"static inline __attribute__((always_inline)) bool {name}(uint32_t w) {{")
            lines.append("  (void)w; return false;")
            lines.append("}")
            continue
        # collapse consecutive runs
        runs = []
        start = prev = members[0]
        for w in members[1:]:
            if w == prev + 1:
                prev = w
                continue
            runs.append((start, prev))
            start = prev = w
        runs.append((start, prev))
        lines.append(f"static inline __attribute__((always_inline)) bool {name}(uint32_t w) {{")
        parts = []
        for lo, hi in runs:
            if lo == hi:
                parts.append(f"w == 0x{lo:02x}")
            else:
                parts.append(f"(0x{lo:02x} <= w && w <= 0x{hi:02x})")
        for i, part in enumerate(parts):
            prefix = "  return " if i == 0 else "         "
            suffix = ";" if i == len(parts) - 1 else " ||"
            lines.append(prefix + part + suffix)
        lines.append("}")
    lines.append("}  // namespace w32wire")
    out.write_text("\n".join(lines) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(Path(sys.argv[1])))
