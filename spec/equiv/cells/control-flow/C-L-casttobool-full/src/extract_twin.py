#!/usr/bin/env python3
"""Extract the twin's `cast_to_bool` verbatim from twin/runtime.inc.

The cell's L leg must be the *real* twin helper, not a re-typed copy.  This
script locates the function by signature, copies its exact text (signature,
body and closing brace), checks it against a pinned SHA-256, and emits it
inside `namespace twin`.

Exit 0 on success; 2 if the function is missing; 3 on a hash mismatch.  A
mismatch is a re-pin: inspect the twin change, then update EXPECTED_SHA256 and
the cell record.
"""
from __future__ import annotations

import hashlib
import sys
from pathlib import Path

EXPECTED_SHA256 = "79b6fb87cd90280d85665d87a7081434bbcb029ae40ced0fc1200328bac16858"
SIGNATURE = "static bool cast_to_bool("


def main() -> int:
    here = Path(__file__).resolve().parent
    root = here.parents[5]
    runtime = root / "spec" / "equiv" / "twin" / "runtime.inc"
    text = runtime.read_text(encoding="utf-8")
    try:
        start = text.index(SIGNATURE)
    except ValueError:
        print(f"extract_twin: {runtime}: missing {SIGNATURE!r}", file=sys.stderr)
        return 2
    brace = text.index("{", start)
    depth = 0
    end = None
    for pos in range(brace, len(text)):
        ch = text[pos]
        if ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0:
                end = pos + 1
                break
    if end is None:
        print("extract_twin: unbalanced braces in runtime.inc", file=sys.stderr)
        return 2
    body = text[start:end]
    digest = hashlib.sha256(body.encode("utf-8")).hexdigest()
    if digest != EXPECTED_SHA256:
        print(
            "extract_twin: twin cast_to_bool changed; re-pin required\n"
            f"  expected {EXPECTED_SHA256}\n  actual   {digest}",
            file=sys.stderr,
        )
        return 3
    out = here.parent / "build" / "twin_cast_to_bool.h"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(
        "// GENERATED by src/extract_twin.py -- do not edit.\n"
        f"// source: spec/equiv/twin/runtime.inc\n"
        f"// function sha256: {digest}\n"
        "#ifndef CELL_TWIN_CAST_TO_BOOL_H\n"
        "#define CELL_TWIN_CAST_TO_BOOL_H\n"
        "#include <cstdint>\n"
        "namespace twin {\n"
        f"{body}\n"
        "}  // namespace twin\n"
        "#endif\n",
        encoding="utf-8",
    )
    print(f"wrote {out} sha256={digest}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
