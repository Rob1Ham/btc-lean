#!/usr/bin/env python3
"""Emit the twin's structural helper functions **verbatim** into a header.

The push-encoding and stack-ops cells need a few of the twin's non-opcode
helpers (`decode_op`, `check_minimal_push`, `is_p2sh`, `is_witness_program`,
`classify_push_only`, `vf_push`, `vf_all`).  Rather than re-transcribing them
(which would make the L leg a paraphrase), this script copies the exact source
text out of `twin/runtime.inc` by name, records the line span of every
function, and emits it as a header.

No function body is edited.  The only requirement is that the caller has
already defined the types/constants the bodies use; cells get those from
`cells/_tools/mk_leaf.py` (`build/twin_ops.h`), whose prelude re-binds
`MAX_STACK_SIZE` / `MAX_SCRIPT_ELEMENT_SIZE` to the cell's bounded domain.

Usage:
  python3 extract_extras.py --runtime twin/runtime.inc --out build/twin_extras.h
"""
from __future__ import annotations
import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

# Functions copied verbatim.  Every one is a predicate/decoder with no
# `std::vector`, no allocation and no external call, so a verbatim copy is a
# faithful L-leg slice.
NAMES = [
    "read_le",              # GetScriptOp little-endian size field (before decode_op)
    "decode_op",            # GetScriptOp (script.cpp:313-363)
    "check_minimal_push",   # script.cpp:373-396
    "is_p2sh",              # script.cpp:224-231
    "is_witness_program",   # script.cpp:250-264
    "classify_push_only",   # script.cpp:266-286
    "vf_push",              # EvalScript condition stack
    "vf_all",               # EvalScript condition stack
]


def sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def extract(lines: list[str], name: str) -> tuple[int, int, str]:
    """Return (first_line, last_line, text) 1-based, by brace matching."""
    pat = re.compile(r"^static\s+[^;]*\b" + re.escape(name) + r"\(")
    for i, line in enumerate(lines):
        if not pat.match(line):
            continue
        depth = 0
        for j in range(i, len(lines)):
            depth += lines[j].count("{") - lines[j].count("}")
            if depth == 0 and j > i:
                return i + 1, j + 1, "\n".join(lines[i:j + 1])
        raise SystemExit(f"{name}: unbalanced braces")
    raise SystemExit(f"{name}: not found in runtime.inc")


def render(runtime: Path) -> tuple[str, dict]:
    lines = runtime.read_text().splitlines()
    out = [
        "// GENERATED by cells/*/_harness/extract_extras.py -- DO NOT EDIT.",
        f"// Source of record: twin/runtime.inc sha256 {sha(runtime)}",
        "// Every function block below is copied verbatim (line spans recorded);",
        "// no body is modified.  Types/constants come from build/twin_ops.h.",
        "// The only added declaration is `PushOnly` (runtime.inc:296), needed by",
        "// the verbatim classify_push_only signature.",
        "#pragma once",
        "",
        "namespace twinleaf {",
        "",
        "enum class PushOnly : uint8_t { Ok, ParseFail, NotPush };  // runtime.inc:296",
        "",
    ]
    spans = {}
    for name in NAMES:
        a, b, text = extract(lines, name)
        spans[name] = [a, b]
        out.append(f"// ---- verbatim twin/runtime.inc:{a}-{b} ({name})")
        # The engine keeps these helpers as plain `static` functions; the twin's
        # real build lets the optimiser decide.  A bounded leaf is a single
        # straight-line body, so the tools must see them inlined: Alive2 does
        # not inline a call to a module-local function and reports it as
        # "Unknown libcall".  The pragma forces always-inline for the *copied*
        # block without touching its text.
        out.append("#pragma clang attribute push(__attribute__((always_inline)), apply_to = function)")
        out.append(text)
        out.append("#pragma clang attribute pop")
        out.append("")
    out.append("}  // namespace twinleaf")
    out.append("")
    meta = {"runtime_inc_sha256": sha(runtime), "spans": spans}
    return "\n".join(out), meta


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--runtime", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--meta")
    a = ap.parse_args()
    text, meta = render(Path(a.runtime))
    Path(a.out).parent.mkdir(parents=True, exist_ok=True)
    Path(a.out).write_text(text)
    if a.meta:
        Path(a.meta).write_text(json.dumps(meta, indent=2, sort_keys=True) + "\n")
    print(f"wrote {a.out} ({len(text)} bytes, {len(NAMES)} verbatim functions)",
          file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
