import sys
from pathlib import Path
HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
sys.path.insert(0, str(HERE))
# [lax-DER] emit DerBatteryCor.lean: 215 raw kernel-decide checks
#   parseDerLax (fromHex "<sig>") = none | some (r, s)
# with (r,s) = the INDEPENDENT python-C oracle values (parse_der_lax_c =
# the Lean raw layer (parseDerLax); 0 pyC-vs-pyLean mismatches on 215).
import gen_der_battery as G
TEST=str(ROOT / 'spec' / 'Test' / 'Crypto' / 'EcdsaTest.lean')
import re
vectors=[]
pat = re.compile(r'\("([A-Za-z0-9-]+)", (true|false), "([0-9a-f]*)", "([0-9a-f]*)", "([0-9a-f]*)"\)')
for line in open(TEST):
    m=pat.search(line)
    if m: vectors.append((m.group(1), m.group(2)=='true', m.group(3)))
assert len(vectors)==215
OUT=str(HERE / 'DerBatteryCor.lean')
with open(OUT,'w') as f:
    f.write('import Bitcoin.Crypto.Ecdsa.Der\n\n')
    f.write('/-!\n')
    f.write('# [lax-DER] DerBatteryCor - the 215-vector ECDSA-lax battery as RAW\n')
    f.write('# kernel-decide checks of the lax-DER parser.\n')
    f.write('# GENERATED by emit_cor.py (oracle gen_der_battery.py) - do not hand-edit.\n')
    f.write('#\n')
    f.write('# Each example pins (by `decide` = kernel-reduction: no native_decide,\n')
    f.write('# kernel-checkable; parseDerLax is structural (not WF-recursive), the\n')
    f.write('# the WF-layer caveat applies only there (modexp/egcd), NOT here)\n')
    f.write('# the Lean `Bitcoin.Crypto.Ecdsa.Der.parseDerLax` to the value of the\n')
    f.write('# INDEPENDENT python-C oracle `parse_der_lax_c` = a transliteration of\n')
    f.write('# Bitcoin Core `ecdsa_signature_parse_der_lax` src/pubkey.cpp:45-185\n')
    f.write('# @ cce32b168 (cce32b16874e85e8a00cfa1a2190f0b6f4dcaf66), fetched\n')
    f.write('# 2026-10-16 (docs/PROVENANCE.md). The oracle\n')
    f.write('# was written against the C, NOT against the Lean; NO Lean code was\n')
    f.write('# consulted. 215/215 pyC-vs-pyLean matches (oracle-vs-transliteration)\n')
    f.write('# = 215/215 parse-level Core-fidelity pins = SGN-109/106/107.\n')
    f.write('#\n')
    f.write('# Corpus (215; 139 verifyLax-accept / 76 reject): 100 valid, 20 wrongkey,\n')
    f.write('# 20 badmsg, 10 highS, 5 overflow-*, 10 der-*, 10 pk-*, 10 pkform-*,\n')
    f.write('# 5 sighashbyte, 16 bip340, 2 zero-r/s, 7 core-detsig. Parse-level:\n')
    f.write('# 203 ok-plain, 4 ok-overflow ((0,0), SGN-106: overflow-000/001/003/004;\n')
    f.write('# overflow-002 = structural reject (C L146 sfit)),\n')
    f.write('# 8 reject (empty x2, rtag, seqtag x2, sfit x2, stagend).\n')
    f.write('#\n')
    f.write('# The relation-layer checks (CoreLax/DerRej = the abstract relational\n')
    f.write('# spec of the C, Bitcoin.Crypto.EcdsaDeep.DerSpec) are the theorems\n')
    f.write('# parseDerLax_rel/parseDerLax_rej + the per-vector CoreLax-decides\n')
    f.write('# (DerRelCor.lean).\n')
    f.write('-/\n\n')
    f.write('namespace Bitcoin.Proofs.EcdsaDeep.DerBatteryCor\n\n')
    f.write('set_option maxRecDepth 100000\n\n')
    f.write('open Bitcoin.Crypto.Ecdsa.Der\n\n')
    f.write('/-- Parse a hex string into a ByteArray (test infra only; copied from\n')
    f.write('the conformance harness, EcdsaTest.lean:36-52, read-only). -/\n')
    f.write('def hexDigitVal (c : Char) : Option Nat :=\n')
    f.write('  let n := c.toNat\n')
    f.write('  if 48 ≤ n ∧ n ≤ 57 then some (n - 48)\n')
    f.write('  else if 97 ≤ n ∧ n ≤ 102 then some (n - 87)\n')
    f.write('  else if 65 ≤ n ∧ n ≤ 70 then some (n - 55)\n')
    f.write('  else none\n\n')
    f.write('def fromHex (s : String) : ByteArray :=\n')
    f.write('  go s.toList ByteArray.empty\n')
    f.write('where\n')
    f.write('  go : List Char → ByteArray → ByteArray\n')
    f.write('    | [], acc => acc\n')
    f.write('    | [_], acc => acc\n')
    f.write('    | a :: b :: rest, acc =>\n')
    f.write('        match hexDigitVal a, hexDigitVal b with\n')
    f.write('        | some hi, some lo => go rest (acc.push ((hi * 16 + lo).toUInt8))\n')
    f.write('        | _, _ => go (b :: rest) acc\n\n')
    f.write('/-! ## The 215 vectors (parseDerLax vs the python-C oracle) -/\n\n')
    ok=0; ov=0; rj=0
    for (name,expected,sighex) in vectors:
        data=bytes.fromhex(sighex)
        try:
            st,(r32,s32),(rc,sc),info = G.parse_der_lax_c(data)
            lean = G.parse_der_lax_lean(data)
            assert lean == (rc,sc), (name, lean, (rc,sc))
            if (rc,sc)==(0,0) and info['overflow']:
                f.write(f'-- {name}: ok, SHARED-OVERFLOW zeroing (SGN-106; C L157-183)\n')
                f.write(f'example : parseDerLax (fromHex\n')
                f.write(f'    "{sighex}") = some (0, 0) := by decide\n\n')
                ov+=1
            else:
                f.write(f'-- {name}: ok-plain\n')
                f.write(f'example : parseDerLax (fromHex\n')
                f.write(f'    "{sighex}") = some ({rc}, {sc}) := by decide\n\n')
                ok+=1
        except G.Reject as rr:
            f.write(f'-- {name}: REJECT-{rr.site} (C {rr.note})\n')
            f.write(f'example : parseDerLax (fromHex\n')
            f.write(f'    "{sighex}") = none := by decide\n\n')
            rj+=1
    f.write('end Bitcoin.Proofs.EcdsaDeep.DerBatteryCor\n')
print(f"emitted {OUT}: ok={ok} overflow={ov} reject={rj} total={ok+ov+rj}")
