def clean(s: str) -> str:
    s = s.strip()
    s = re.sub(r"\s+", " ", s)
    return s


def split_cells(line: str) -> list[str]:
    """Split a markdown table row on '|' delimiters, tolerating empty cells.
    (Cells in these tables never contain literal ASCII pipes; the vertical
    bar they use for concatenation is U+2016 '‖'.)"""
    body = line.strip()
    if body.startswith("|"):
        body = body[1:]
    if body.endswith("|"):
        body = body[:-1]
    return [clean(c) for c in body.split("|")]


def yq(s):  # yaml-quote
    if s is None:
        return "null"
    if isinstance(s, int):
        return str(s)
    if s == "":
        return '""'
    if re.fullmatch(r"[A-Za-z0-9_.@:/×≤≥∀≠∅¬,\[\]\- ]+", s) and not s.startswith(("'", '"')):
        return f'"{s}"'
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def parse_source(src: dict) -> list[dict]:
    path = RESEARCH / src["file"]
    rows, section, header = [], "?", None
    for line in path.read_text().splitlines():
        m = SECTION_RE.match(line)
        if m:
            section = m.group(1).strip()
        # table header line -> canonical column names for the current table
        if re.match(r"^\|\s*(Rule )?ID\s*\|", line):
            header = []
            for h in split_cells(line):
                k = re.sub(r"\s*\(.*$", "", h.lower().strip())
                k = re.sub(r"@.*$", "", k).strip()
                if k.startswith("rule id") or k == "id":
                    k = "id"
                elif k.startswith("rule") or k == "check":
                    k = "check"
                elif k.startswith("core location"):
                    k = "core_loc"
                elif k.startswith("one-line") or k.startswith("spec"):
                    k = "spec"
                elif k.startswith("bip") or k == "ref":
                    k = "bip_cve"
                elif k in ("diff", "d"):
                    k = "diff"
                elif k.startswith("lean note"):
                    k = "lean_note"
                elif k.startswith("why excluded"):
                    k = "why_excluded"
                header.append(k)
            continue
        m = ROW_RE.match(line)
        if not m:
            continue
        rid = m.group(1)
        prefix = rid.split("-")[0]
        if prefix not in src["prefixes"]:
            continue
        cells = split_cells(line)
        if header and len(header) == len(cells):
            c = dict(zip(header, cells))
            def pick(*keys):
                for k in keys:
                    if c.get(k):
                        return c[k]
                return ""
            row = dict(
                id=rid,
                check=pick("check"),
                core_loc=pick("core_loc", "why_excluded"),
                spec=pick("spec"),
                bip_cve=pick("bip_cve", "why_excluded"),
                sixth=cells[5] if len(cells) > 5 else "",
            )
        else:
            # ragged row: positional fallback (check, core, spec, bip, note)
            pad = cells + [""] * 6
            row = dict(id=rid, check=pad[1], core_loc=pad[2], spec=pad[3],
                       bip_cve=pad[4], sixth=pad[5] if len(pad) > 5 else "")
        if src["diff_from_note"]:
            note = row["sixth"]
            dm = re.search(r"d=(\d)", note)
            row["diff"] = int(dm.group(1)) if dm else None
            row["lean_note"] = note
        else:
            d = row["sixth"]
            row["diff"] = int(d) if d.isdigit() else None
            row["lean_note"] = ""
        row["source"] = f"{src['file']}:AppendixB"
        row["section"] = section
        row["commit"] = src["commit"]
        rows.append(row)
    return rows


def build_base_row(r: dict) -> dict:
    """One row of the DB as the PRE-OVRBACK generator built it: report row
    (or HAND_ROWS literal) + the hand OVERRIDES table — i.e. the state a
    regen would produce WITHOUT rules_overrides_sync.py. The 04:35 regen
    (GATES F-G4-01/F-G4-02) emitted exactly this, and the committed yaml
    had drifted away from it by 460+ rows. Used by build_row() below and
    by spec/scripts/backfill_overrides.py (the delta between this and the
    committed yaml IS the sync layer)."""
    rid = r["id"]
    if r.get("_hand"):
        # HAND_ROWS literal: full row data, no report source. Curation
        # fields (status/lean_target/notes) ride the same two layers.
        row = dict(
            id=rid,
            summary=r["summary"],
            check=r["check"],
            core_ref=r["core_ref"],
            bip_cve=r["bip_cve"],
            test_vector_ids=list(r.get("test_vector_ids") or []),
            status="planned",
            difficulty=r.get("difficulty"),
            consensus=r.get("consensus", True),
            source=r["source"],
        )
        ov = OVERRIDES.get(rid, {})
        if ov.get("status"):
            row["status"] = ov["status"]
        if ov.get("lean_target"):
            row["lean_target"] = ov["lean_target"]
        if ov.get("notes"):
            row["notes"] = ov["notes"]
        return row
    # report row: the old main() row construction, verbatim
    ov = OVERRIDES.get(rid, {})
    row = dict(
        id=rid,
        summary=r["spec"] or r["check"],
        check=r["check"],
        core_ref=f"{r['core_loc']}@{r['commit']}" if r["core_loc"] else "",
        bip_cve=r["bip_cve"],
        lean_target=ov.get("lean_target"),
        test_vector_ids=[],
        status=ov.get("status", "planned"),
        difficulty=r["diff"],
        consensus=not any(r["section"].startswith(s) for s in NOT_CONSENSUS_SECTIONS),
        source=r["source"] + " §" + r["section"],
    )
    if r["lean_note"]:
        row["lean_note"] = r["lean_note"]
    if ov.get("notes"):
        row["notes"] = ov["notes"]
    return row


def build_row(r: dict) -> dict:
    """build_base_row + the OVERRIDES_SYNC overlay (which WINS over the
    hand table — it mirrors the committed yaml = the curation record)."""
    row = build_base_row(r)
    sync = (OVERRIDES_SYNC or {}).get(r["id"])
    if sync:
        for k, v in sync.items():
            row[k] = v
    return row


def emit_row(row: dict) -> list[str]:
    """Row dict -> yaml lines. Verbatim old main() emission for the 11
    original fields (yq() etc., never a yaml emitter), extended with the
    curation fields the old generator never emitted (implemented_by,
    non-empty test_vector_ids) and the conditional lean_note/notes. Field
    order here is the canonical generator order; the committed yaml has
    13 hand-edited orders — --check therefore compares rows semantically
    (parsed), never textually."""
    lines = [
        f"- id: {row['id']}",
        f"  summary: {yq(row['summary'])}",
        f"  check: {yq(row['check'])}",
        f"  core_ref: {yq(row['core_ref'])}",
        f"  bip_cve: {yq(row['bip_cve'])}",
        f"  lean_target: {yq(row.get('lean_target')) if row.get('lean_target') else 'null'}",
        "  test_vector_ids: "
        + ("[]" if not row.get("test_vector_ids")
           else "[" + ", ".join(yq(t) for t in row["test_vector_ids"]) + "]"),
        f"  status: {row['status']}",
    ]
    if "implemented_by" in row:
        lines.append(f"  implemented_by: {yq(row['implemented_by'])}")
    lines += [
        f"  difficulty: {row['difficulty'] if row.get('difficulty') is not None else 'null'}",
        f"  consensus: {'true' if row.get('consensus') else 'false'}",
    ]
    if row.get("lean_note"):
        lines.append(f"  lean_note: {yq(row['lean_note'])}")
    if row.get("notes"):
        lines.append(f"  notes: {yq(row['notes'])}")
    lines.append(f"  source: {yq(row['source'])}")
    return lines


def check(existing: Path, regen_rows: list[dict]) -> int:
    """Semantic compare (parsed rows, never text) of a fresh regen against
    the target DB: id set, id order, field set, field value. Any drift ->
    exit 1. This is the GATES gate-4 regen-safety probe: a regen is safe
    iff this exits 0."""
    try:
        import yaml
    except ImportError:
        print("FATAL: --check needs PyYAML (python3-yaml)", file=sys.stderr)
        return 2
    yaml_rows = yaml.safe_load(existing.read_text())["rules"]
    rids = [r["id"] for r in regen_rows]
    yids = [r["id"] for r in yaml_rows]
    rmap = {r["id"]: r for r in regen_rows}
    ymap = {r["id"]: r for r in yaml_rows}
    n_drift = 0
    shown = 0

    def drift(msg: str) -> None:
        nonlocal shown
        shown += 1
        if shown <= 40:
            print(f"DRIFT: {msg}", file=sys.stderr)

    only_regen = [i for i in rids if i not in ymap]
    only_yaml = [i for i in yids if i not in rmap]
    if only_regen:
        n_drift += 1
        drift(f"{len(only_regen)} rows in the regen but NOT in {existing} "
              f"(a regen would ADD them): {only_regen[:12]}"
              + (" ..." if len(only_regen) > 12 else ""))
    if only_yaml:
        n_drift += 1
        drift(f"{len(only_yaml)} rows in {existing} but NOT in the regen "
              f"(a regen would DROP them): {only_yaml[:12]}"
              + (" ..." if len(only_yaml) > 12 else ""))
    if not only_regen and not only_yaml and rids != yids:
        n_drift += 1
        first = next(i for i, (a, b) in enumerate(zip(rids, yids)) if a != b)
        drift(f"row order differs (first divergence at index {first}: "
              f"regen={rids[first]} yaml={yids[first]})")
    field_drift = 0
    for rid in yids:
        if rid not in rmap:
            continue
        a, b = rmap[rid], ymap[rid]
        if a == b:
            continue
        keys = list(a.keys()) + [k for k in b.keys() if k not in a]
        diffs = [(k, a.get(k), b.get(k)) for k in keys if a.get(k) != b.get(k)]
        if diffs:
            field_drift += 1
            n_drift += 1
            for k, av, bv in diffs:
                drift(f"{rid}.{k}: regen={repr(av)[:80]} yaml={repr(bv)[:80]}")
    if shown > 40:
        print(f"DRIFT: ... ({shown - 40} further drift lines suppressed)",
              file=sys.stderr)
    print(f"\ncheck vs {existing}: {len(yaml_rows)} yaml rows, {len(regen_rows)} "
          f"regen rows, {field_drift} rows with field drift"
          + ("" if n_drift == 0 else " — NOT a fixed point (exit 1)"))
    return 1 if n_drift else 0


def regen(out_path: Path) -> list[dict]:
    """The old main() body, factored out: parse sources -> build rows
    (base + sync overlay) -> emit to out_path. Returns the built rows
    (--check uses them). NEVER writes anything but out_path."""
    all_rows: list[dict] = []
    for src in SOURCES:
        rows = parse_source(src)
        print(f"{src['file']}: {len(rows)} rows ({'/'.join(src['prefixes'])})")
        all_rows.extend(rows)

    # de-dup + sanity
    ids = [r["id"] for r in all_rows]
    dupes = {i for i in ids if ids.count(i) > 1}
    if dupes:
        print(f"FATAL: duplicate rule IDs: {sorted(dupes)}", file=sys.stderr)
        raise SystemExit(1)
    hand_ids = [r["id"] for r in HAND_ROWS]
    hdupes = {i for i in hand_ids if hand_ids.count(i) > 1}
    if hdupes:
        print(f"FATAL: duplicate HAND_ROWS IDs: {sorted(hdupes)}", file=sys.stderr)
        raise SystemExit(1)
    clash = set(hand_ids) & set(ids)
    if clash:
        print(f"FATAL: HAND_ROWS IDs also in report tables: {sorted(clash)}",
              file=sys.stderr)
        raise SystemExit(1)

    # _hand rows are emitted after the report rows (their historical file
    # position: the tail of the yaml, rows 8762-8893)
    all_rows += HAND_ROWS
    built = [build_row(r) for r in all_rows]

    lines = [
        "# rules.yaml — btc-lean traceability database (GENERATED FILE)",
        "#",
        "# Source of truth: the Appendix B tables of research/05..09-*.md",
        "# plus the HAND_ROWS of spec/scripts/extract_rules.py, extracted",
        "# by that script (re-run to regenerate; --check = the safety probe).",
        "# Hand curation lives in (1) the script's OVERRIDES table",
        "# (historical) and (2) spec/scripts/rules_overrides_sync.py,",
        "# GENERATED by spec/scripts/backfill_overrides.py as the mirror of this",
        "# file's curation — edit the yaml, then re-run the backfill.",
        "# (REGEN SAFETY: GATES F-G4-01/F-G4-02, the 04:35 regen incident;",
        "# see the extract_rules.py docstring.)",
        "#",
        "# Ground-truth pin: Bitcoin Core v32.99 @ cce32b168 (DECISIONS.md D-001).",
        "# Rows carry the commit their line anchors were verified at:",
        "#   cce32b168 (report 05) / cce32b168 (reports 06-09, same tree days apart).",
        "#",
        "# Schema (per row):",
        "#   id            rule ID (immutable, never renumbered)",
        "#   summary       one-line spec statement",
        "#   check         Core-side rule name / short label",
        "#   core_ref      file:function:lines@<commit> in the pinned Core tree",
        "#   bip_cve       BIP / CVE / attribution string ('-' = none given)",
        "#   lean_target   fully-qualified Lean decl that must carry @[rule \"id\"]",
        "#                 (null until assigned; required once status >= implemented)",
        "#   test_vector_ids  corpus selectors (W07; [] when empty)",
        "#   status        planned | stubbed | implemented | proven | obsolete",
        "#   implemented_by  curation lane that flipped the row (sync layer)",
        "#   difficulty    B-track 1..5 estimate (null if unlisted)",
        "#   consensus     false for the catalogued policy/DoS boundary rows",
        "#   lean_note     report 05 'Lean note' column, when present",
        "#   notes         curation notes (promotions, divergences, ...)",
        "#   source        report + section the row was extracted from",
        f"# Rows: {len(built)}",
        "rules:",
    ]
    ns_counts: dict[str, int] = {}
    for row in built:
        rid = row["id"]
        ns = rid.rsplit("-", 1)[0]
        ns_counts[ns] = ns_counts.get(ns, 0) + 1
        lines += emit_row(row)

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(lines) + "\n")
    print(f"\nwrote {out_path} ({len(built)} rows)")
    print("per-namespace coverage:")
    for ns in sorted(ns_counts):
        n_impl = sum(1 for row in built
                     if row["id"].startswith(ns + "-")
                     and row["status"] in ("implemented", "proven"))
        print(f"  {ns}: {ns_counts[ns]} rows ({n_impl} implemented)")
    return built


