#!/usr/bin/env python3
"""Generate the public rule-census and wallet theorem indexes.

The indexes are derived from the checked rule databases, not from a separate
hand-maintained ledger:

* ``spec/db/rules.yaml`` for the consensus census, including rows explicitly
  marked ``consensus: false`` as boundary evidence;
* ``spec/db/rules-wallet.yaml`` and ``spec/db/rules-wallet.obligations.tsv``
  for the wallet rows and their obligation declarations.

Run with ``--check`` in CI to reject stale generated pages.
"""

from __future__ import annotations

import argparse
import csv
import difflib
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
DB = ROOT / "spec" / "db"
DOCS = ROOT / "docs"

THEOREMS = DOCS / "THEOREMS.md"
WALLET_THEOREMS = DOCS / "WALLET-THEOREMS.md"


def load_yaml(path: Path) -> list[dict]:
    data = yaml.safe_load(path.read_text())
    return data["rules"]


def cell(value) -> str:
    text = "" if value is None else str(value)
    text = " ".join(text.split())
    return text.replace("|", "\\|")


def targets(row: dict) -> list[str]:
    value = row.get("lean_target")
    if not value:
        return []
    return [part.strip() for part in str(value).split(",") if part.strip()]


def module_of(declaration: str) -> str:
    if "." not in declaration:
        return "—"
    return declaration.rsplit(".", 1)[0]


def target_cell(row: dict) -> str:
    names = targets(row)
    if not names:
        return "—"
    return "<br>".join(f"`{cell(name)}`" for name in names)


def module_cell(row: dict) -> str:
    modules = sorted({module_of(name) for name in targets(row)})
    if not modules:
        return "—"
    return "<br>".join(f"`{cell(name)}`" for name in modules)


def is_boundary(row: dict) -> bool:
    return row.get("consensus") is False


def surface_cell(row: dict) -> str:
    return "`boundary`" if is_boundary(row) else "`consensus`"


def header(title: str, intro: str, counts: str) -> list[str]:
    return [
        f"# {title}",
        "",
        "<!-- Generated by spec/scripts/theorem_index.py; do not hand-edit. -->",
        "",
        intro,
        "",
        counts,
        "",
    ]


def consensus_page(rows: list[dict]) -> str:
    proven = [row for row in rows if row.get("status") == "proven"]
    proven_consensus = [row for row in proven if not is_boundary(row)]
    proven_boundary = [row for row in proven if is_boundary(row)]
    obsolete = [row for row in rows if row.get("status") == "obsolete"]
    other = [row for row in rows if row.get("status") not in {"proven", "obsolete"}]
    boundary = [row for row in rows if is_boundary(row)]

    lines = header(
        "Rule-census theorem index",
        "Every row in the `spec/db/rules.yaml` rule census, with its cited Lean "
        "target. Rows marked `consensus: false` are boundary evidence about policy, "
        "availability, trust, or anti-DoS surfaces; they are not consensus claims. "
        "The target is an index into the proof surface; it is not a claim that the "
        "target paraphrases every word of the row summary. Residual rows are listed "
        "separately in [RESIDUALS.md](RESIDUALS.md) and [RESIDUALS-EVIDENCE.md](RESIDUALS-EVIDENCE.md).",
        f"Rows: **{len(rows)}** total, **{len(proven)}** proven "
        f"(**{len(proven_consensus)}** consensus, **{len(proven_boundary)}** boundary), "
        f"**{len(obsolete)}** obsolete, **{len(other)}** other; "
        f"**{len(boundary)}** rows are marked `consensus: false`.",
    )
    lines += [
        "## Proven consensus rows",
        "",
        "| ID | Claim | Core anchor | Lean target | Module |",
        "|---|---|---|---|---|",
    ]
    for row in sorted(proven_consensus, key=lambda item: item["id"]):
        lines.append(
            f"| `{cell(row['id'])}` | {cell(row.get('summary'))} | "
            f"{cell(row.get('core_ref'))} | {target_cell(row)} | {module_cell(row)} |"
        )
    lines += [
        "",
        "## Proven boundary rows",
        "",
        "Rows marked `consensus: false`; their targets are boundary evidence, not "
        "consensus claims.",
        "",
        "| ID | Claim | Core anchor | Lean target | Module |",
        "|---|---|---|---|---|",
    ]
    for row in sorted(proven_boundary, key=lambda item: item["id"]):
        lines.append(
            f"| `{cell(row['id'])}` | {cell(row.get('summary'))} | "
            f"{cell(row.get('core_ref'))} | {target_cell(row)} | {module_cell(row)} |"
        )
    lines += [
        "",
        "## Obsolete rows",
        "",
        "| ID | Surface | Claim | Core anchor |",
        "|---|---|---|---|",
    ]
    for row in sorted(obsolete, key=lambda item: item["id"]):
        lines.append(
            f"| `{cell(row['id'])}` | {surface_cell(row)} | {cell(row.get('summary'))} | "
            f"{cell(row.get('core_ref'))} |"
        )
    if other:
        lines += [
            "",
            "## Other rows",
            "",
            "| ID | Surface | Status | Claim |",
            "|---|---|---|---|",
        ]
        for row in sorted(other, key=lambda item: item["id"]):
            lines.append(
                f"| `{cell(row['id'])}` | {surface_cell(row)} | {cell(row.get('status'))} | "
                f"{cell(row.get('summary'))} |"
            )
    lines.append("")
    return "\n".join(lines)


def load_obligations() -> dict[str, dict]:
    path = DB / "rules-wallet.obligations.tsv"
    with path.open(newline="") as handle:
        return {row["id"]: row for row in csv.DictReader(handle, delimiter="\t")}


def wallet_page(rows: list[dict]) -> str:
    obligations = load_obligations()
    status_counts: dict[str, int] = {}
    grade_counts: dict[str, int] = {}
    for row in rows:
        status_counts[row.get("status", "unknown")] = status_counts.get(row.get("status", "unknown"), 0) + 1
        grade = obligations.get(row["id"], {}).get("grade", "unregistered")
        grade_counts[grade] = grade_counts.get(grade, 0) + 1

    counts = ", ".join(f"**{value}** {name}" for name, value in sorted(status_counts.items()))
    grades = ", ".join(f"**{value}** {name}" for name, value in sorted(grade_counts.items()))
    lines = header(
        "Wallet theorem and obligation index",
        "Wallet rows from `spec/db/rules-wallet.yaml`, joined to the obligation "
        "register in `spec/db/rules-wallet.obligations.tsv`. A `checked` or "
        "`differential` grade is evidence of a reviewed boundary; it is not a "
        "theorem that the wallet implementation equals Bitcoin Core.",
        f"Rows: **{len(rows)}** ({counts}); obligation grades: {grades}.",
    )
    lines += [
        "| ID | Claim | Status | Grade | Declaration | Model module |",
        "|---|---|---|---|---|---|",
    ]
    for row in sorted(rows, key=lambda item: item["id"]):
        obligation = obligations.get(row["id"], {})
        declaration = obligation.get("declaration") or row.get("lean_target") or "—"
        module = obligation.get("model_module") or "—"
        lines.append(
            f"| `{cell(row['id'])}` | {cell(row.get('summary'))} | "
            f"{cell(row.get('status'))} | {cell(obligation.get('grade', 'unregistered'))} | "
            f"{cell(declaration)} | `{cell(module)}` |"
        )
    lines.append("")
    return "\n".join(lines)


def emit(path: Path, text: str, check: bool) -> bool:
    current = path.read_text() if path.exists() else ""
    if current == text:
        return True
    if check:
        diff = list(difflib.unified_diff(
            current.splitlines(), text.splitlines(),
            fromfile=str(path.relative_to(ROOT)), tofile="generated", lineterm=""
        ))
        print("\n".join(diff[:80]), file=sys.stderr)
        return False
    path.write_text(text)
    print(f"wrote {path.relative_to(ROOT)}")
    return True


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if generated pages are stale")
    args = parser.parse_args()

    consensus = load_yaml(DB / "rules.yaml")
    wallet = load_yaml(DB / "rules-wallet.yaml")
    ok = emit(THEOREMS, consensus_page(consensus), args.check)
    ok &= emit(WALLET_THEOREMS, wallet_page(wallet), args.check)
    if args.check and not ok:
        print("theorem-index: generated pages are stale", file=sys.stderr)
        return 1
    if args.check:
        print(f"theorem-index: {len(consensus)} census rows, {len(wallet)} wallet rows")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
