#!/usr/bin/env python3
"""Generate a machine-readable residual ledger and evidence matrix.

The prose source is ``docs/RESIDUALS.md``.  The generated YAML gives tools a
stable ID -> {claim, core, target, missing link} record, and the generated
Markdown page keeps the evidence visible next to the theorem indexes.
"""

from __future__ import annotations

import argparse
import difflib
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "docs" / "RESIDUALS.md"
OUT_YAML = ROOT / "spec" / "db" / "residuals.yaml"
OUT_MD = ROOT / "docs" / "RESIDUALS-EVIDENCE.md"

FIELD_RE = re.compile(r"^- (claim|core|target|missing link):\s*(.*)$")
SECTION_RE = re.compile(r"^##\s+(\S+)\s*$", re.MULTILINE)
ENTRY_RE = re.compile(r"^###\s+(\S+)\s*$", re.MULTILINE)


def parse_residuals(text: str) -> list[dict]:
    records: list[dict] = []
    section_matches = list(SECTION_RE.finditer(text))
    for section_index, section_match in enumerate(section_matches):
        section = section_match.group(1)
        section_end = (
            section_matches[section_index + 1].start()
            if section_index + 1 < len(section_matches)
            else len(text)
        )
        block = text[section_match.end():section_end]
        entry_matches = list(ENTRY_RE.finditer(block))
        for entry_index, entry_match in enumerate(entry_matches):
            entry_end = (
                entry_matches[entry_index + 1].start()
                if entry_index + 1 < len(entry_matches)
                else len(block)
            )
            body = block[entry_match.end():entry_end]
            fields: dict[str, str] = {}
            current = None
            for line in body.splitlines():
                match = FIELD_RE.match(line)
                if match:
                    current = match.group(1)
                    fields[current] = match.group(2).strip()
                elif current and line.strip():
                    fields[current] += " " + line.strip()
            missing = ["claim", "core", "target", "missing link"]
            absent = [name for name in missing if not fields.get(name)]
            if absent:
                raise ValueError(f"{entry_match.group(1)}: missing fields {absent}")
            records.append({
                "id": entry_match.group(1),
                "section": section,
                "claim": fields["claim"],
                "core": fields["core"],
                "target": fields["target"],
                "missing_link": fields["missing link"],
            })
    return records


def yaml_page(records: list[dict]) -> str:
    data = {
        "source": "docs/RESIDUALS.md",
        "row_count": len(records),
        "residuals": records,
    }
    body = yaml.safe_dump(data, sort_keys=False, allow_unicode=True, width=120)
    return (
        "# Generated by spec/scripts/residuals_index.py from docs/RESIDUALS.md.\n"
        "# Do not hand-edit; run `python3 spec/scripts/residuals_index.py`.\n"
        + body
    )


def md_cell(value: str) -> str:
    return " ".join(value.split()).replace("|", "\\|")


def md_page(records: list[dict]) -> str:
    counts: dict[str, int] = {}
    for record in records:
        counts[record["section"]] = counts.get(record["section"], 0) + 1
    summary = ", ".join(f"{name} {count}" for name, count in counts.items())
    lines = [
        "# Residual evidence matrix",
        "",
        "<!-- Generated by spec/scripts/residuals_index.py; do not hand-edit. -->",
        "",
        f"The {len(records)} consensus residuals in [RESIDUALS.md](RESIDUALS.md), with "
        "the cited target and the missing link kept in one place. The machine-readable copy is "
        "[`spec/db/residuals.yaml`](../spec/db/residuals.yaml). A residual means the "
        "row claim is true of Bitcoin Core but the current Lean target does not yet "
        "entail the whole claim; it is not a theorem-count claim or a narrowing of the "
        "Core rule.",
        "",
        f"Rows: **{len(records)}** ({summary}).",
        "",
        "## Evidence matrix",
        "",
        "| ID | Claim | Core anchor | Cited target |",
        "|---|---|---|---|",
    ]
    for record in records:
        lines.append(
            f"| [`{md_cell(record['id'])}`](#{record['id'].lower()}) | "
            f"{md_cell(record['claim'])} | {md_cell(record['core'])} | "
            f"{md_cell(record['target'])} |"
        )
    current = None
    for record in records:
        if record["section"] != current:
            current = record["section"]
            lines += ["", f"## {current}"]
        lines += [
            "",
            f"### {record['id']}",
            "",
            f"- **Claim:** {record['claim']}",
            f"- **Core:** {record['core']}",
            f"- **Target:** {record['target']}",
            f"- **Missing link:** {record['missing_link']}",
        ]
    lines.append("")
    return "\n".join(lines)


def emit(path: Path, text: str, check: bool) -> bool:
    current = path.read_text() if path.exists() else ""
    if current == text:
        return True
    if check:
        diff = list(difflib.unified_diff(
            current.splitlines(), text.splitlines(),
            fromfile=str(path.relative_to(ROOT)), tofile="generated", lineterm=""
        ))
        print("\n".join(diff[:80]), file=sys.stderr)
        return False
    path.write_text(text)
    print(f"wrote {path.relative_to(ROOT)}")
    return True


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if generated files are stale")
    args = parser.parse_args()

    records = parse_residuals(SOURCE.read_text())
    expected = 25
    if len(records) != expected:
        print(f"residuals-index: expected {expected} rows, found {len(records)}", file=sys.stderr)
        return 1
    ok = emit(OUT_YAML, yaml_page(records), args.check)
    ok &= emit(OUT_MD, md_page(records), args.check)
    if args.check and not ok:
        print("residuals-index: generated files are stale", file=sys.stderr)
        return 1
    if args.check:
        print(f"residuals-index: {len(records)} residuals")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
