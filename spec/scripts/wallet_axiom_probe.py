#!/usr/bin/env python3
"""Generate (or check) the wallet ``#print axioms`` probe.

The wallet axiom manifest covers every *public theorem/lemma declaration*
in the two additive wallet source trees:

  * ``spec/core/Bitcoin/Wallet/**/*.lean``          -> ``Bitcoin.Wallet.*``
  * ``spec/proofs/BitcoinProofs/Wallet/**/*.lean``  -> ``BitcoinProofs.Wallet.*``

This is the same source scope as ``wallet_sorry_lint.py`` and
``wallet_crosscheck.py``, restricted to theorem/lemma declarations because
the manifest contract is a theorem contract (``spec/db/axiom-manifest-wallet.txt``).
Private theorems cannot be named from another module, so they are excluded;
their proof terms still contribute to the transitive axiom footprint of any
public theorem that uses them.  Local scratch modules named ``Probe*.lean``
are not deliverables and are excluded on purpose (they duplicate theorem
names from the real proof modules); the report records that exclusion.

The generated file is an ordinary Lean file.  It imports every module in
scope (there is no ``Bitcoin.Wallet`` / ``BitcoinProofs.Wallet`` umbrella in
this tree -- see ``docs/WALLET.md``) and emits one ``#print axioms`` line per
public theorem.  Run it from ``spec/proofs``:

    lake env lean ../scripts/wallet_axiom_probe.lean

Usage:
    python3 spec/scripts/wallet_axiom_probe.py --write
    python3 spec/scripts/wallet_axiom_probe.py --check

``--check`` exits 1 if the committed probe is stale with respect to the
source trees.  It does not invoke Lean.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent.parent
PROBE = REPO / "spec" / "scripts" / "wallet_axiom_probe.lean"
TREES = (
    (REPO / "spec" / "core" / "Bitcoin" / "Wallet", "Bitcoin.Wallet"),
    (REPO / "spec" / "proofs" / "BitcoinProofs" / "Wallet", "BitcoinProofs.Wallet"),
)

NAMESPACE_RE = re.compile(r"^namespace\s+(\S+)\s*$")
END_RE = re.compile(r"^end(?:\s+(\S+))?\s*$")
# @[attr] and visibility/modifier keywords may precede the declaration.
DECL_RE = re.compile(
    r"^(?:@\[[^\]]*\]\s*)*"
    r"(?:(private|protected|noncomputable|unsafe|partial)\s+)*"
    r"(theorem|lemma)\s+([^\s:(\[{]+)"
)


def strip_comments(line: str, in_block: bool) -> tuple[str, bool]:
    """Return the code part of *line* and the block-comment state after it."""
    out: list[str] = []
    i = 0
    while i < len(line):
        if in_block:
            j = line.find("-/", i)
            if j == -1:
                return "", True
            in_block = False
            i = j + 2
            continue
        if line.startswith("--", i):
            break
        if line.startswith("/-", i):
            in_block = True
            i += 2
            continue
        out.append(line[i])
        i += 1
    return "".join(out), in_block


def in_scope_files() -> list[tuple[str, Path]]:
    """Return ``(module, path)`` pairs for every non-scratch wallet file."""
    files: list[tuple[str, Path]] = []
    for tree, prefix in TREES:
        if not tree.is_dir():
            continue
        for path in sorted(tree.rglob("*.lean")):
            if ".lake" in path.parts:
                continue
            if path.name.startswith("Probe"):
                continue
            module = ".".join((prefix + "/" + path.relative_to(tree).as_posix()).removesuffix(".lean").split("/"))
            files.append((module, path))
    return files


def declarations(path: Path) -> list[str]:
    """Public theorem/lemma names declared in *path*, fully qualified."""
    names: list[str] = []
    stack: list[str] = []
    in_block = False
    for raw in path.read_text().splitlines():
        code, in_block = strip_comments(raw, in_block)
        stripped = code.strip()
        match = NAMESPACE_RE.match(stripped)
        if match:
            parent = stack[-1] if stack else ""
            name = match.group(1)
            stack.append(f"{parent}.{name}" if parent else name)
            continue
        match = END_RE.match(stripped)
        if match:
            if stack:
                stack.pop()
            continue
        match = DECL_RE.match(code)
        if not match:
            continue
        if match.group(1) == "private":
            continue
        name = match.group(3)
        names.append(f"{stack[-1]}.{name}" if stack else name)
    return names


def collect() -> list[tuple[str, Path, list[str]]]:
    result: list[tuple[str, Path, list[str]]] = []
    for module, path in in_scope_files():
        result.append((module, path, declarations(path)))
    return result


def render() -> str:
    entries = collect()
    imports = sorted({module for module, _, _ in entries})
    lines = [
        "-- GENERATED by spec/scripts/wallet_axiom_probe.py -- do not edit.",
        "--",
        "-- Scope: every public theorem/lemma in the two wallet source trees.",
        "-- Run from spec/proofs: lake env lean ../scripts/wallet_axiom_probe.lean",
        "",
    ]
    lines.extend(f"import {module}" for module in imports)
    lines.append("")
    count = 0
    for module, path, names in entries:
        if not names:
            continue
        lines.append(f"-- {path.relative_to(REPO).as_posix()}")
        for name in names:
            lines.append(f"#print axioms {name}")
            count += 1
        lines.append("")
    if count == 0:
        lines.append("-- no wallet theorem declarations in scope")
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--write", action="store_true", help="write the probe file")
    group.add_argument("--check", action="store_true", help="check the probe is current")
    args = parser.parse_args()

    rendered = render()
    if args.write:
        PROBE.write_text(rendered)
        entries = collect()
        n_decls = sum(len(names) for _, _, names in entries)
        print(
            f"wallet-axiom-probe: wrote {PROBE.relative_to(REPO)} "
            f"({len(entries)} modules, {n_decls} theorem declarations)"
        )
        return 0

    old = PROBE.read_text() if PROBE.is_file() else ""
    if old == rendered:
        entries = collect()
        n_decls = sum(len(names) for _, _, names in entries)
        print(
            f"wallet-axiom-probe: OK ({len(entries)} modules, "
            f"{n_decls} theorem declarations)"
        )
        return 0
    print(
        f"wallet-axiom-probe: FAIL stale {PROBE.relative_to(REPO)} "
        "(run wallet_axiom_probe.py --write)",
        file=sys.stderr,
    )
    return 1


if __name__ == "__main__":
    sys.exit(main())
