#!/usr/bin/env bash
# wallet_axiom_manifest.sh - axiom gate for wallet declarations only.
#
#   wallet_axiom_manifest.sh --check-static
#       Validate the committed wallet manifest (spec/db/axiom-manifest-wallet.txt)
#       without invoking Lean. The check is not vacuous: it also requires the
#       committed probe (spec/scripts/wallet_axiom_probe.lean) to be current and
#       to cover exactly the declarations listed in the manifest.
#
#   wallet_axiom_manifest.sh [--probe]
#       Dynamic mode (the default): run the committed #print axioms probe in the
#       proofs workspace and require every actual axiom footprint to equal the
#       reviewed footprint in the manifest. Any sorryAx, Lean.ofReduceBool,
#       Lean.trustCompiler, _native, or other unexpected axiom fails the gate.
#
#   wallet_axiom_manifest.sh --update
#       Deliberate regeneration: run the probe, review the result, and rewrite
#       the declaration entries in the manifest. This never edits the probe.
#
# Scope: every public theorem/lemma declaration in
# spec/core/Bitcoin/Wallet/**/*.lean and
# spec/proofs/BitcoinProofs/Wallet/**/*.lean, generated by
# spec/scripts/wallet_axiom_probe.py. Private theorems cannot be named from the
# probe module; local scratch modules named Probe*.lean are not deliverables.
# Consensus declarations are never probed.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
MANIFEST="$ROOT/db/axiom-manifest-wallet.txt"
PROBE="$ROOT/scripts/wallet_axiom_probe.lean"
MODE="${1:---probe}"

if [ "$MODE" != "--check-static" ] && [ "$MODE" != "--probe" ] && [ "$MODE" != "--update" ]; then
  echo "usage: wallet_axiom_manifest.sh [--check-static|--probe|--update]" >&2
  exit 2
fi

if [ ! -s "$MANIFEST" ]; then
  echo "wallet-axiom: missing or empty $MANIFEST" >&2
  exit 1
fi
if [ ! -s "$PROBE" ]; then
  echo "wallet-axiom: missing or empty $PROBE" >&2
  exit 1
fi

if [ "$MODE" = "--check-static" ]; then
  python3 "$ROOT/scripts/wallet_axiom_probe.py" --check
elif [ "$MODE" = "--update" ]; then
  python3 "$ROOT/scripts/wallet_axiom_probe.py" --write
fi

python3 - "$MANIFEST" "$MODE" "$ROOT" <<'PY'
from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

manifest_path = Path(sys.argv[1])
mode = sys.argv[2]
root = Path(sys.argv[3])
probe_path = root / "scripts" / "wallet_axiom_probe.lean"

EXPECTED = ["propext", "Classical.choice", "Quot.sound"]
FORBIDDEN = ("sorryAx", "Lean.ofReduceBool", "Lean.trustCompiler", "_native")
EXPECTED_RE = re.compile(r"^expected:\s*\[(.*)\]$")
DECL_RE = re.compile(r"^decl:\s*([A-Za-z0-9_.'«»?!]+)\s*->\s*\[(.*)\]$")
PROBE_RE = re.compile(r"^\s*#print axioms\s+(\S+)\s*$")


def split_set(text: str) -> list[str]:
    return [part.strip() for part in text.split(",") if part.strip()]


text = manifest_path.read_text()
errors: list[str] = []
content_lines = [
    line.strip()
    for line in text.splitlines()
    if line.strip() and not line.strip().startswith("#")
]
for marker in FORBIDDEN:
    if any(marker in line for line in content_lines):
        errors.append(f"forbidden axiom/trust marker in manifest: {marker}")

expected: list[str] | None = None
decls: list[tuple[str, list[str]]] = []
for lineno, line in enumerate(text.splitlines(), 1):
    stripped = line.strip()
    if not stripped or stripped.startswith("#"):
        continue
    match = EXPECTED_RE.fullmatch(stripped)
    if match:
        if expected is not None:
            errors.append(f"{manifest_path}:{lineno}: duplicate expected line")
        expected = split_set(match.group(1))
        continue
    match = DECL_RE.fullmatch(stripped)
    if match:
        decls.append((match.group(1), split_set(match.group(2))))
        continue
    errors.append(f"{manifest_path}:{lineno}: unrecognised line: {stripped[:100]}")

if expected is None:
    errors.append("missing expected: [..] line")
elif expected != EXPECTED:
    errors.append(
        f"expected axiom set is {expected}, must be exactly {EXPECTED}"
    )

seen: set[str] = set()
for name, axioms in decls:
    if name in seen:
        errors.append(f"duplicate declaration entry: {name}")
    seen.add(name)
    outside = sorted(set(axioms) - set(EXPECTED))
    if outside:
        errors.append(f"{name}: axioms outside permitted set: {outside}")

probe_names = [
    match.group(1)
    for match in (
        PROBE_RE.match(line) for line in probe_path.read_text().splitlines()
    )
    if match
]
probe_seen: set[str] = set()
for name in probe_names:
    if name in probe_seen:
        errors.append(f"duplicate #print axioms entry in probe: {name}")
    probe_seen.add(name)

missing_from_manifest = sorted(probe_seen - seen)
extra_in_manifest = sorted(seen - probe_seen)
if mode != "--update":
    if missing_from_manifest:
        errors.append(
            f"probe declarations missing from manifest: {missing_from_manifest}"
        )
    if extra_in_manifest:
        errors.append(
            f"manifest declarations missing from probe: {extra_in_manifest}"
        )

if errors:
    for error in errors:
        print(f"wallet-axiom: FAIL {error}", file=sys.stderr)
    print("wallet-axiom: FAIL", file=sys.stderr)
    sys.exit(1)

if mode == "--check-static":
    print(
        f"wallet-axiom[static]: OK ({len(decls)} declaration(s); "
        f"permitted axioms {EXPECTED})"
    )
    sys.exit(0)

if not probe_names:
    print("wallet-axiom[probe]: no wallet declarations to probe; static contract OK")
    sys.exit(0)

proc = subprocess.run(
    ["lake", "env", "lean", str(probe_path)],
    cwd=str(root / "proofs"),
    text=True,
    capture_output=True,
)
if proc.returncode != 0:
    print(proc.stdout, file=sys.stderr)
    print(proc.stderr, file=sys.stderr)
    print("wallet-axiom[probe]: Lean failed", file=sys.stderr)
    sys.exit(1)

output = proc.stdout + proc.stderr
entry_re = re.compile(
    r"'([^']+)' (does not depend on any axioms|depends on axioms: \[([^\]]*)\])"
)
actual_by_name: dict[str, list[str]] = {}
for match in entry_re.finditer(output):
    name = match.group(1)
    actual_by_name[name] = (
        [] if match.group(2).startswith("does not depend") else split_set(match.group(3))
    )

manifest_expected = dict(decls)
failed = False
for name in probe_names:
    expected_axioms = manifest_expected.get(name, [])
    if name not in actual_by_name:
        print(
            f"wallet-axiom[probe]: no #print axioms output for {name}",
            file=sys.stderr,
        )
        failed = True
        continue
    actual = actual_by_name[name]
    outside = sorted(set(actual) - set(EXPECTED))
    if outside:
        print(
            f"wallet-axiom[probe]: {name} uses forbidden axioms {outside}",
            file=sys.stderr,
        )
        failed = True
        continue
    if mode != "--update" and sorted(actual) != sorted(expected_axioms):
        print(
            f"wallet-axiom[probe]: {name}: actual {actual} != manifest "
            f"{expected_axioms}",
            file=sys.stderr,
        )
        failed = True

if failed:
    print("wallet-axiom[probe]: FAIL", file=sys.stderr)
    sys.exit(1)

if mode == "--update":
    header = text.split("\nexpected:", 1)[0].rstrip() + "\n\n"
    body = [header, f"expected: [{', '.join(EXPECTED)}]\n"]
    for name in probe_names:
        body.append(f"decl: {name} -> [{', '.join(actual_by_name[name])}]\n")
    manifest_path.write_text("".join(body))
    print(
        f"wallet-axiom[update]: wrote {len(probe_names)} declaration(s) to "
        f"{manifest_path}"
    )
    sys.exit(0)

print(
    f"wallet-axiom[probe]: OK ({len(decls)} declaration(s), "
    f"permitted {EXPECTED})"
)
PY
